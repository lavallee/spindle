"""Public documentation stays aligned with what Spindle implements."""

from __future__ import annotations

import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit


ROOT = Path(__file__).parents[1]
DOCS = ROOT / "docs"
PUBLIC_PAGES = (
    "index.html",
    "rationale.html",
    "house.html",
    "catalog.html",
    "lifecycle.html",
    "how-it-works.html",
    "evaluation.html",
    "guide.html",
)


class _Links(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.targets: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag not in {"a", "link", "script"}:
            return
        values = dict(attrs)
        target = values.get("href") or values.get("src")
        if target:
            self.targets.append(target)


def test_public_html_parses_links_locally_and_routes_through_lifecycle():
    for name in PUBLIC_PAGES:
        page = DOCS / name
        text = page.read_text(encoding="utf-8")
        parser = _Links()
        parser.feed(text)
        parser.close()

        assert 'href="lifecycle.html"' in text
        for target in parser.targets:
            parts = urlsplit(target)
            if parts.scheme or parts.netloc or target.startswith(("data:", "#")):
                continue
            assert (page.parent / parts.path).exists(), f"{name}: missing {target}"


